-- SkyLink v2 schema translated to Oracle SQL for the DBMS coursework report.
-- NOTE: the running application uses SQLite (see schema_sqlite.sql). This Oracle script mirrors
-- the same tables and constraints for documentation / ER diagrams. It has NOT been executed
-- against an Oracle instance; run it in a dedicated schema and fix any dialect issues.
CREATE TABLE airports(code CHAR(3) PRIMARY KEY, city VARCHAR2(80) NOT NULL, name VARCHAR2(150) NOT NULL,
  country VARCHAR2(80) NOT NULL, country_code CHAR(2) NOT NULL, lat NUMBER(9,6) NOT NULL, lon NUMBER(9,6) NOT NULL,
  tz_minutes NUMBER(4) NOT NULL, region VARCHAR2(20) NOT NULL, is_small NUMBER(1) DEFAULT 0 NOT NULL);
CREATE TABLE airlines(code VARCHAR2(3) PRIMARY KEY, name VARCHAR2(80) NOT NULL, tier NUMBER(4,2) NOT NULL, hub CHAR(3));
CREATE TABLE users(id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email VARCHAR2(254) NOT NULL,
  password_hash VARCHAR2(255) NOT NULL, full_name VARCHAR2(80) NOT NULL, phone VARCHAR2(20), dob DATE,
  gender VARCHAR2(10), nationality VARCHAR2(40), passport_no VARCHAR2(12),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, last_login_at TIMESTAMP, CONSTRAINT uq_users_email UNIQUE(email));
CREATE TABLE flights(id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, flight_number VARCHAR2(10) NOT NULL,
  airline_code VARCHAR2(3) NOT NULL REFERENCES airlines(code), origin CHAR(3) NOT NULL REFERENCES airports(code),
  destination CHAR(3) NOT NULL REFERENCES airports(code), dep_local TIMESTAMP NOT NULL, arr_local TIMESTAMP NOT NULL,
  duration_min NUMBER(5) NOT NULL, stops NUMBER(1) DEFAULT 0 NOT NULL, via CHAR(3),
  base_fare NUMBER(10,2) NOT NULL, fare NUMBER(10,2) NOT NULL, prev_fare NUMBER(10,2) NOT NULL,
  aircraft VARCHAR2(40) NOT NULL, layout VARCHAR2(10) NOT NULL, status VARCHAR2(12) DEFAULT 'SCHEDULED' NOT NULL,
  created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL,
  CONSTRAINT chk_route CHECK(origin <> destination), CONSTRAINT uq_flight UNIQUE(flight_number, origin, destination, dep_local));
CREATE INDEX idx_flights_route ON flights(origin, destination, dep_local);
CREATE TABLE flight_seats(id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flight_id NUMBER NOT NULL REFERENCES flights(id) ON DELETE CASCADE, seat_no VARCHAR2(4) NOT NULL,
  row_no NUMBER(3) NOT NULL, col CHAR(1) NOT NULL, cabin VARCHAR2(10) NOT NULL, kind VARCHAR2(10) DEFAULT 'standard' NOT NULL,
  price_add NUMBER(10,2) DEFAULT 0 NOT NULL, status VARCHAR2(10) DEFAULT 'AVAILABLE' NOT NULL,
  hold_until TIMESTAMP, booking_id NUMBER, CONSTRAINT uq_seat UNIQUE(flight_id, seat_no),
  CONSTRAINT chk_seat_status CHECK(status IN ('AVAILABLE','HELD','BOOKED','OCCUPIED')));
CREATE TABLE bookings(id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, pnr CHAR(6) NOT NULL UNIQUE,
  user_id NUMBER NOT NULL REFERENCES users(id), flight_id NUMBER NOT NULL REFERENCES flights(id),
  status VARCHAR2(16) NOT NULL, pax_count NUMBER(2) NOT NULL, base_amount NUMBER(12,2) NOT NULL,
  seat_amount NUMBER(12,2) NOT NULL, taxes NUMBER(12,2) NOT NULL, discount NUMBER(12,2) DEFAULT 0 NOT NULL,
  total NUMBER(12,2) NOT NULL, promo_code VARCHAR2(20), contact_email VARCHAR2(254) NOT NULL,
  contact_phone VARCHAR2(20) NOT NULL, hold_until TIMESTAMP, created_at TIMESTAMP NOT NULL,
  confirmed_at TIMESTAMP, cancelled_at TIMESTAMP, refund_amount NUMBER(12,2), refund_percent NUMBER(3),
  CONSTRAINT chk_booking_status CHECK(status IN ('PENDING_PAYMENT','CONFIRMED','CANCELLED','EXPIRED')));
CREATE INDEX idx_bookings_user ON bookings(user_id, created_at);
CREATE TABLE passengers(id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id NUMBER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE, full_name VARCHAR2(80) NOT NULL,
  age NUMBER(3) NOT NULL, gender VARCHAR2(10), passport_no VARCHAR2(12), seat_no VARCHAR2(4) NOT NULL,
  seat_price NUMBER(10,2) DEFAULT 0 NOT NULL, fare NUMBER(10,2) NOT NULL, ticket_number VARCHAR2(16));
CREATE TABLE payments(id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, booking_id NUMBER NOT NULL REFERENCES bookings(id),
  kind VARCHAR2(8) DEFAULT 'PAYMENT' NOT NULL, method VARCHAR2(12) NOT NULL, upi_id VARCHAR2(60), card_last4 CHAR(4),
  bank VARCHAR2(60), amount NUMBER(12,2) NOT NULL, status VARCHAR2(10) NOT NULL, txn_ref VARCHAR2(40) NOT NULL,
  failure_reason VARCHAR2(200), created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL,
  CONSTRAINT chk_pay_status CHECK(status IN ('PENDING','SUCCESS','FAILED')));
CREATE TABLE fare_alerts(id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id NUMBER NOT NULL REFERENCES users(id),
  email VARCHAR2(254) NOT NULL, origin CHAR(3) NOT NULL, destination CHAR(3) NOT NULL, travel_date DATE NOT NULL,
  flight_id NUMBER REFERENCES flights(id), target_price NUMBER(10,2), baseline_price NUMBER(10,2) NOT NULL,
  last_notified_price NUMBER(10,2) NOT NULL, active NUMBER(1) DEFAULT 1 NOT NULL, created_at TIMESTAMP NOT NULL,
  last_notified_at TIMESTAMP, notify_count NUMBER(5) DEFAULT 0 NOT NULL);
CREATE TABLE fare_history(id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flight_id NUMBER NOT NULL REFERENCES flights(id) ON DELETE CASCADE, fare NUMBER(10,2) NOT NULL, recorded_at TIMESTAMP NOT NULL);
CREATE INDEX idx_fare_history ON fare_history(flight_id, recorded_at);
CREATE TABLE promos(code VARCHAR2(20) PRIMARY KEY, kind VARCHAR2(8) NOT NULL, value NUMBER(10,2) NOT NULL,
  max_discount NUMBER(10,2), min_amount NUMBER(10,2) DEFAULT 0 NOT NULL, international_only NUMBER(1) DEFAULT 0 NOT NULL,
  first_booking_only NUMBER(1) DEFAULT 0 NOT NULL, description VARCHAR2(200) NOT NULL, active NUMBER(1) DEFAULT 1 NOT NULL);
CREATE TABLE email_outbox(id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, to_email VARCHAR2(254) NOT NULL,
  subject VARCHAR2(300) NOT NULL, body_html CLOB NOT NULL, mode VARCHAR2(8) NOT NULL, status VARCHAR2(10) NOT NULL,
  error VARCHAR2(500), file_path VARCHAR2(300), created_at TIMESTAMP NOT NULL);
