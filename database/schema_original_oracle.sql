-- SkyLink Oracle schema: execute in a dedicated project schema, not SYS/SYSTEM.
CREATE TABLE AIRLINE (
 airline_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 airline_code VARCHAR2(5) NOT NULL UNIQUE,
 airline_name VARCHAR2(100) NOT NULL UNIQUE
);
CREATE TABLE AIRPORT (
 airport_code CHAR(3) PRIMARY KEY,
 city VARCHAR2(80) NOT NULL,
 airport_name VARCHAR2(150) NOT NULL,
 country VARCHAR2(80) DEFAULT 'India' NOT NULL
);
CREATE TABLE AIRCRAFT (
 aircraft_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 airline_id NUMBER NOT NULL REFERENCES AIRLINE(airline_id),
 aircraft_model VARCHAR2(80) NOT NULL,
 seat_capacity NUMBER(4) NOT NULL CHECK (seat_capacity > 0)
);
CREATE TABLE FLIGHT (
 flight_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 airline_id NUMBER NOT NULL REFERENCES AIRLINE(airline_id),
 flight_number VARCHAR2(15) NOT NULL,
 origin_airport CHAR(3) NOT NULL REFERENCES AIRPORT(airport_code),
 destination_airport CHAR(3) NOT NULL REFERENCES AIRPORT(airport_code),
 CONSTRAINT chk_flight_route CHECK(origin_airport <> destination_airport),
 CONSTRAINT uq_airline_flight UNIQUE(airline_id,flight_number)
);
CREATE TABLE FLIGHT_SCHEDULE (
 schedule_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 flight_id NUMBER NOT NULL REFERENCES FLIGHT(flight_id),
 aircraft_id NUMBER NOT NULL REFERENCES AIRCRAFT(aircraft_id),
 departure_time TIMESTAMP NOT NULL,
 arrival_time TIMESTAMP NOT NULL,
 duration_minutes NUMBER(5) NOT NULL CHECK(duration_minutes > 0),
 base_fare NUMBER(10,2) NOT NULL CHECK(base_fare >= 0),
 stops NUMBER(2) DEFAULT 0 NOT NULL CHECK(stops >= 0),
 schedule_status VARCHAR2(20) DEFAULT 'SCHEDULED' NOT NULL,
 CONSTRAINT chk_schedule_status CHECK(schedule_status IN ('SCHEDULED','CANCELLED','DELAYED')),
 CONSTRAINT chk_schedule_times CHECK(arrival_time > departure_time)
);
CREATE TABLE SEAT (
 seat_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 aircraft_id NUMBER NOT NULL REFERENCES AIRCRAFT(aircraft_id),
 seat_number VARCHAR2(5) NOT NULL,
 seat_class VARCHAR2(20) DEFAULT 'ECONOMY' NOT NULL,
 seat_status VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL,
 CONSTRAINT uq_aircraft_seat UNIQUE(aircraft_id,seat_number),
 CONSTRAINT chk_seat_status CHECK(seat_status IN ('AVAILABLE','BLOCKED')),
 CONSTRAINT chk_seat_class CHECK(seat_class IN ('ECONOMY','BUSINESS','FIRST'))
);
CREATE TABLE PASSENGER (
 passenger_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name VARCHAR2(100) NOT NULL,
 email VARCHAR2(254) NOT NULL UNIQUE,
 phone VARCHAR2(20) NOT NULL,
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE BOOKING (
 booking_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 booking_reference VARCHAR2(20) NOT NULL UNIQUE,
 passenger_id NUMBER NOT NULL REFERENCES PASSENGER(passenger_id),
 booking_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 booking_status VARCHAR2(20) DEFAULT 'CONFIRMED' NOT NULL,
 total_amount NUMBER(10,2) NOT NULL CHECK(total_amount >= 0),
 CONSTRAINT chk_booking_status CHECK(booking_status IN ('CONFIRMED','CANCELLED','PENDING'))
);
CREATE TABLE BOOKING_FLIGHT (
 booking_flight_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 booking_id NUMBER NOT NULL REFERENCES BOOKING(booking_id),
 schedule_id NUMBER NOT NULL REFERENCES FLIGHT_SCHEDULE(schedule_id),
 passenger_id NUMBER NOT NULL REFERENCES PASSENGER(passenger_id),
 seat_number VARCHAR2(5),
 fare_amount NUMBER(10,2) NOT NULL CHECK(fare_amount >= 0)
);
CREATE TABLE TICKET (
 ticket_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 booking_flight_id NUMBER NOT NULL UNIQUE REFERENCES BOOKING_FLIGHT(booking_flight_id),
 ticket_number VARCHAR2(30) NOT NULL UNIQUE,
 issued_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 ticket_status VARCHAR2(20) DEFAULT 'NOT_ISSUED' NOT NULL
);
CREATE TABLE PAYMENT (
 payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 booking_id NUMBER NOT NULL REFERENCES BOOKING(booking_id),
 amount NUMBER(10,2) NOT NULL CHECK(amount >= 0),
 payment_method VARCHAR2(30),
 payment_status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
 transaction_reference VARCHAR2(100),
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT chk_payment_status CHECK(payment_status IN ('PENDING','SUCCESS','FAILED','REFUNDED'))
);
CREATE TABLE SEAT_SWAP_REQUEST (
 swap_request_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 booking_flight_id NUMBER NOT NULL REFERENCES BOOKING_FLIGHT(booking_flight_id),
 requested_by_passenger NUMBER NOT NULL REFERENCES PASSENGER(passenger_id),
 target_seat_number VARCHAR2(5) NOT NULL,
 reason VARCHAR2(300),
 request_status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 reviewed_by VARCHAR2(100),
 CONSTRAINT chk_swap_status CHECK(request_status IN ('PENDING','APPROVED','REJECTED','CANCELLED'))
);
CREATE TABLE FARE_HISTORY (
 fare_history_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 schedule_id NUMBER NOT NULL REFERENCES FLIGHT_SCHEDULE(schedule_id),
 recorded_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 fare_amount NUMBER(10,2) NOT NULL CHECK(fare_amount >= 0),
 source_label VARCHAR2(50) DEFAULT 'ACADEMIC_SAMPLE'
);
CREATE TABLE CONNECTION_RISK (
 connection_risk_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 booking_id NUMBER REFERENCES BOOKING(booking_id),
 inbound_schedule_id NUMBER NOT NULL REFERENCES FLIGHT_SCHEDULE(schedule_id),
 outbound_schedule_id NUMBER NOT NULL REFERENCES FLIGHT_SCHEDULE(schedule_id),
 layover_minutes NUMBER(5) NOT NULL,
 risk_score NUMBER(5,2) NOT NULL CHECK(risk_score BETWEEN 0 AND 100),
 risk_label VARCHAR2(20) NOT NULL,
 assessed_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE USER_ACCOUNT (
 user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR2(254) NOT NULL UNIQUE,
 password_hash VARCHAR2(255) NOT NULL,
 user_role VARCHAR2(20) DEFAULT 'PASSENGER' NOT NULL,
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT chk_user_role CHECK(user_role IN ('PASSENGER','STAFF','ADMIN'))
);
CREATE INDEX idx_flight_route ON FLIGHT(origin_airport,destination_airport);
CREATE INDEX idx_schedule_departure ON FLIGHT_SCHEDULE(departure_time);
CREATE INDEX idx_booking_passenger ON BOOKING(passenger_id);
CREATE INDEX idx_bookingflight_schedule ON BOOKING_FLIGHT(schedule_id);

